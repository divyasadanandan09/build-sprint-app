import { test, expect } from '@playwright/test';

test('opens the public landing page and sends the button directly to WhatsApp with Hi', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText("Turn client testimonials into new enquiries.");
  const link = page.getByRole('link', { name: 'Paste one review.' });
  await expect(link).toHaveAttribute('href', /^https:\/\/wa\.me\/[1-9]\d{7,14}\?text=Hi$/);
  await expect(link).not.toHaveAttribute('aria-disabled');
  const target = await link.getAttribute('href');
  let clickedTarget: string | undefined;
  await page.route('https://wa.me/**', async route => {
    clickedTarget = route.request().url();
    await route.abort(); // Prove the outgoing link; real phone handoff and sending remain owner checks.
  });
  await link.click();
  await expect.poll(() => clickedTarget).toBe(target);
  expect(errors).toEqual([]);
  console.log('PASS: live 390px page; button navigates directly to wa.me with text=Hi; no JavaScript errors. Actual phone handoff/reply requires an owner phone check.');
});

