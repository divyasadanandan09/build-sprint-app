test('spaces and lifts one moving card, keeps labels attached, and plays labelled demo media', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto('/');
  const carousel = page.getByRole('region', { name: 'Testimonial examples' });
  const card = page.locator('.text-card');
  const firstX = await card.evaluate(element => element.getBoundingClientRect().x);
  await expect.poll(() => card.evaluate(element => element.getBoundingClientRect().x)).toBeLessThan(firstX - 4);
  const movingCard = await card.boundingBox();
  expect(movingCard).not.toBeNull();
  await page.mouse.move(movingCard!.x + movingCard!.width / 2, movingCard!.y + movingCard!.height / 2);
  await expect(carousel).toHaveAttribute('data-paused', 'true');
  await expect(card).toHaveClass(/is-selected/);
  await expect.poll(() => card.evaluate(element => element.style.transform)).toContain('scale(1.06)');
  expect(await page.locator('.carousel-cards').evaluate(element => getComputedStyle(element).transform)).toBe('none');
  await expect(page.locator('.video-card')).not.toHaveClass(/is-selected/);
  await expect(card.locator('.card-annotation')).toHaveText('text message');
  const frozen = await card.evaluate(element => element.style.transform);
  const later = await card.evaluate(element => new Promise<string>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve(element.style.transform)))));
  expect(later).toBe(frozen);
  const spaces = await page.locator('.text-card, .voice-card, .video-card').evaluateAll(elements => {
    const rectangles = elements.map(e => e.getBoundingClientRect()).sort((a, b) => a.left - b.left);
    return rectangles.slice(1).map((r, i) => r.left - rectangles[i].right);
  });
  expect(Math.min(...spaces)).toBeGreaterThan(8);
  const voice = page.locator('.voice-card');
  await voice.hover();
  await expect(voice).toHaveClass(/is-selected/);
  await expect(card).not.toHaveClass(/is-selected/);
  await expect(voice.getByText('Demo')).toBeVisible();
  await expect.poll(async () => await voice.locator('audio').evaluate((media: HTMLMediaElement) => !media.paused) || await voice.getByText('Tap to play').isVisible()).toBe(true);
  if (await voice.locator('audio').evaluate((media: HTMLMediaElement) => media.paused)) await voice.getByRole('button', { name: 'Play demo' }).click();
  await expect.poll(() => voice.locator('audio').evaluate((media: HTMLMediaElement) => media.currentTime)).toBeGreaterThan(.2);
  const video = page.locator('.video-card');
  await video.hover();
  await expect.poll(() => voice.locator('audio').evaluate((media: HTMLMediaElement) => media.paused)).toBe(true);
  await expect.poll(async () => await video.locator('video').evaluate((media: HTMLMediaElement) => !media.paused) || await video.getByText('Tap to play').isVisible()).toBe(true);
  if (await video.locator('video').evaluate((media: HTMLMediaElement) => media.paused)) await video.getByRole('button', { name: 'Play demo' }).click();
  await expect.poll(() => video.locator('video').evaluate((media: HTMLMediaElement) => media.currentTime)).toBeGreaterThan(.2);
  await page.mouse.move(0, 0);
  await expect.poll(() => video.locator('video').evaluate((media: HTMLMediaElement) => media.paused)).toBe(true);
  await expect(carousel).toHaveAttribute('data-paused', 'false');
  await card.dispatchEvent('pointerdown', { pointerType: 'touch' });
  await expect(card).toHaveClass(/is-selected/);
  await expect(carousel).toHaveAttribute('data-paused', 'true');
  await card.dispatchEvent('pointerdown', { pointerType: 'touch' });
  await expect(carousel).toHaveAttribute('data-paused', 'false');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(carousel).toHaveAttribute('data-paused', 'true');
  const beforeSwipe = await card.evaluate(element => element.style.transform);
  await carousel.dispatchEvent('pointerdown', { pointerType: 'touch', clientX: 200, clientY: 100 });
  await carousel.dispatchEvent('pointerup', { pointerType: 'touch', clientX: 100, clientY: 100 });
  expect(await card.evaluate(element => element.style.transform)).not.toBe(beforeSwipe);
  // A fresh tab proves hover-video playback without prior sound permission.
  const fresh = await page.context().newPage();
  await fresh.setViewportSize({ width: 1440, height: 1000 });
  await fresh.goto('/');
  const demoPhoto = fresh.locator('.before-after-preview img');
  await demoPhoto.evaluate((img: HTMLImageElement) => img.decode());
  expect(await demoPhoto.evaluate((img: HTMLImageElement) => img.naturalWidth > 0)).toBe(true);
  await expect(fresh.locator('.before-card')).toContainText('AI-generated illustration');
  const centerTop = await fresh.locator('.text-card').evaluate(e => e.getBoundingClientRect().top);
  const sideTop = await fresh.locator('.voice-card').evaluate(e => e.getBoundingClientRect().top);
  expect(sideTop).toBeGreaterThan(centerTop + 10);
  await expect(fresh.locator('body')).not.toContainText(/fictional/i);
  await expect(fresh.locator('.video-card .sender')).toContainText('Meera');
  await expect(fresh.locator('.before-card .sender')).toContainText('Meera');
  await expect(fresh.locator('.voice-card .sender')).toContainText('Ananya');
  await expect(fresh.locator('.group-trailing')).toContainText('Can someone recommend a good pediatrician nearby?');
  const freshVideo = fresh.locator('.video-card');
  await freshVideo.hover();
  await expect.poll(() => freshVideo.locator('video').evaluate((media: HTMLMediaElement) => media.currentTime)).toBeGreaterThan(.2);
  if (await freshVideo.locator('video').evaluate((media: HTMLMediaElement) => media.muted)) {
    await expect(freshVideo.getByText('Tap for sound')).toBeVisible();
    await freshVideo.getByRole('button', { name: 'Play demo with sound' }).click();
    await expect.poll(() => freshVideo.locator('video').evaluate((media: HTMLMediaElement) => media.muted)).toBe(false);
  }
  await fresh.close();
  console.log('PASS: separated cards; one selected card lifts while track freezes; attached handwritten labels; demo audio/video playback with click fallback; stop on exit; touch pause/resume; reduced-motion support.');
});
